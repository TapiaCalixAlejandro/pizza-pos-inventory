-- ==============================
-- INVENTORY SERVICE
-- V1: Create inventory tables
-- Database: PostgreSQL
-- ==============================

-- ==============================
-- 1. INVENTORIES
-- Stores ingredients and their current stock information.
-- ==============================
CREATE TABLE inventories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    unit VARCHAR(20) NOT NULL,
    current_stock NUMERIC(12, 3) NOT NULL DEFAULT 0,
    reserved_stock NUMERIC(12, 3) NOT NULL DEFAULT 0,
    minimum_stock NUMERIC(12, 3) NOT NULL DEFAULT 0,
    cost_per_unit NUMERIC(12, 4) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_inventory_name UNIQUE (name),
    CONSTRAINT chk_inventory_current_stock CHECK (current_stock >= 0),
    CONSTRAINT chk_inventory_reserved_stock CHECK (reserved_stock >= 0),
    CONSTRAINT chk_inventory_reserved_not_exceed_current CHECK (reserved_stock <= current_stock),
    CONSTRAINT chk_inventory_minimum_stock CHECK (minimum_stock >= 0),
    CONSTRAINT chk_inventory_cost_per_unit CHECK (cost_per_unit >= 0)
);

-- ==============================
-- 2. RECIPES
-- Stores recipes associated with products from Catalog.
-- product_id is an external microservice identifier.
-- ==============================
CREATE TABLE recipes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    name VARCHAR(150) NOT NULL,
    status VARCHAR(20) NOT NULL,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- =============================
-- 3. RECIPE INGREDIENTS
-- Stores the ingredients and quantities required by a recipe.
-- =============================
CREATE TABLE recipe_ingredients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipe_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    quantity NUMERIC(12, 3) NOT NULL,

    CONSTRAINT fk_recipe_ingredients_recipe
        FOREIGN KEY (recipe_id)
        REFERENCES recipes (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_recipe_ingredients_inventory
        FOREIGN KEY (ingredient_id)
        REFERENCES inventories (id)
        ON DELETE CASCADE,

    CONSTRAINT uk_recipe_ingredient UNIQUE (recipe_id, ingredient_id),
    CONSTRAINT chk_recipe_ingredient_quantity CHECK (quantity > 0)
);

-- =================================
-- 4. INVENTORY RESERVATIONS
-- Stores ingredient reservations associated with orders.
-- order_id is an external microservice identifier.
-- =================================
CREATE TABLE inventory_reservations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL,
    status VARCHAR(20) NOT NULL,
    expires_at TIMESTAMP,
    confirmed_at TIMESTAMP,
    released_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_inventory_reservation_order UNIQUE (order_id)
);

-- ========================================
-- 5. INVENTORY RESERVATION DETAILS
-- Stores the ingredients and quantities of each reservation.
-- ========================================
CREATE TABLE inventory_reservation_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reservation_id BIGINT NOT NULL,
    ingredient_id BIGINT NOT NULL,
    quantity NUMERIC(12, 3) NOT NULL,

    CONSTRAINT fk_reservation_details_reservation
        FOREIGN KEY (reservation_id)
        REFERENCES inventory_reservations (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_reservation_details_inventory
        FOREIGN KEY (ingredient_id)
        REFERENCES inventories (id)
        ON DELETE RESTRICT,

    CONSTRAINT uk_reservation_ingredient UNIQUE (reservation_id, ingredient_id),
    CONSTRAINT chk_reservation_detail_quantity CHECK (quantity > 0)
);

-- ==============================
-- 6. INVENTORY MOVEMENTS
-- Stores the historical movements of ingredient stock.
-- ==============================
CREATE TABLE inventory_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ingredient_id BIGINT NOT NULL,
    type VARCHAR(20) NOT NULL,
    quantity NUMERIC(12, 3) NOT NULL,
    previous_stock NUMERIC(12, 3) NOT NULL,
    new_stock NUMERIC(12, 3) NOT NULL,
    reference_id BIGINT,
    description VARCHAR(300),
    order_id BIGINT,
    reservation_id BIGINT,
    created_by BIGINT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_inventory_movements_inventory
        FOREIGN KEY (ingredient_id)
        REFERENCES inventories (id)
        ON DELETE CASCADE,

    CONSTRAINT fk_inventory_movements_reservation
        FOREIGN KEY (reservation_id)
        REFERENCES inventory_reservations (id)
        ON DELETE CASCADE,

    CONSTRAINT chk_inventory_movement_quantity CHECK (quantity > 0),
    CONSTRAINT chk_inventory_movement_previous_stock CHECK (previous_stock >= 0),
    CONSTRAINT chk_inventory_movement_new_stock CHECK (new_stock >= 0)
);

-- ==============================
-- INDEXES
-- ==============================

-- Inventory
CREATE INDEX idx_inventories_status ON inventories (status);

-- Recipes
CREATE INDEX idx_recipes_product_id ON recipes (product_id);
CREATE INDEX idx_recipes_status ON recipes (status);

-- Recipe ingredients
CREATE INDEX idx_recipe_ingredients_ingredient_id ON recipe_ingredients (ingredient_id);

-- Reservations
CREATE INDEX idx_inventory_reservations_status ON inventory_reservations (status);
CREATE INDEX idx_inventory_reservations_expires_at ON inventory_reservations (expires_at);

-- Reservation details
CREATE INDEX idx_reservation_details_ingredient_id ON inventory_reservation_details (ingredient_id);

-- Inventory movements
CREATE INDEX idx_inventory_movements_ingredient_id ON inventory_movements (ingredient_id);
CREATE INDEX idx_inventory_movements_order_id ON inventory_movements (order_id);
CREATE INDEX idx_inventory_movements_reservation_id ON inventory_movements (reservation_id);
CREATE INDEX idx_inventory_movements_created_at ON inventory_movements (created_at);